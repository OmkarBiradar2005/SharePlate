const PDFDocument = require('pdfkit');
const Donation = require('../models/Donation');
const User = require('../models/User');
const Review = require('../models/Review');

// @desc    Generate donation report PDF
// @route   GET /api/reports/donations
// @access  Private
const generateDonationReport = async (req, res) => {
  try {
    const { startDate, endDate } = req.query;
    
    let query = { donorId: req.user._id };
    
    if (startDate && endDate) {
      query.createdAt = {
        $gte: new Date(startDate),
        $lte: new Date(endDate)
      };
    }

    const donations = await Donation.find(query)
      .populate('acceptedBy', 'name')
      .sort({ createdAt: -1 });

    // Calculate statistics
    const totalDonations = donations.length;
    const completed = donations.filter(d => d.status === 'completed').length;
    const totalMeals = donations.reduce((sum, d) => sum + (d.estimatedMeals || 0), 0);
    const carbonSaved = donations.reduce((sum, d) => sum + (d.carbonFootprintSaved || 0), 0);

    // Create PDF
    const doc = new PDFDocument({ margin: 50 });
    
    // Set response headers
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=donation-report-${Date.now()}.pdf`);
    
    doc.pipe(res);

    // Title
    doc.fontSize(24).text('SharePlate Donation Report', { align: 'center' });
    doc.moveDown();
    
    // User info
    doc.fontSize(12).text(`Donor: ${req.user.name}`);
    doc.text(`Email: ${req.user.email}`);
    doc.text(`Report Generated: ${new Date().toLocaleString()}`);
    if (startDate && endDate) {
      doc.text(`Period: ${new Date(startDate).toLocaleDateString()} - ${new Date(endDate).toLocaleDateString()}`);
    }
    doc.moveDown();

    // Summary statistics
    doc.fontSize(16).text('Summary Statistics', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(12);
    doc.text(`Total Donations: ${totalDonations}`);
    doc.text(`Completed Donations: ${completed}`);
    doc.text(`Success Rate: ${totalDonations > 0 ? ((completed / totalDonations) * 100).toFixed(2) : 0}%`);
    doc.text(`Total Meals Saved: ${totalMeals}`);
    doc.text(`Carbon Footprint Saved: ${carbonSaved.toFixed(2)} kg CO2`);
    doc.moveDown();

    // Donations table
    doc.fontSize(16).text('Donation Details', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(10);

    donations.forEach((donation, index) => {
      doc.text(`${index + 1}. ${donation.foodName}`, { continued: true });
      doc.text(` - ${donation.status}`, { align: 'right' });
      doc.text(`   Quantity: ${donation.quantity}, Type: ${donation.foodType}`);
      doc.text(`   Date: ${donation.createdAt.toLocaleDateString()}`);
      if (donation.acceptedBy) {
        doc.text(`   Picked by: ${donation.acceptedBy.name}`);
      }
      doc.moveDown(0.5);
      
      // Page break if needed
      if (doc.y > 700) {
        doc.addPage();
      }
    });

    // Footer
    doc.fontSize(8).text('Generated by SharePlate - Fighting Food Waste Together', {
      align: 'center',
      baseline: 'bottom'
    });

    doc.end();
  } catch (error) {
    console.error(error);
    res.status(500).json({
      success: false,
      message: 'Server error'
    });
  }
};

// @desc    Export donations to CSV
// @route   GET /api/reports/export-csv
// @access  Private
const exportToCSV = async (req, res) => {
  try {
    const { startDate, endDate } = req.query;
    
    let query = { donorId: req.user._id };
    
    if (startDate && endDate) {
      query.createdAt = {
        $gte: new Date(startDate),
        $lte: new Date(endDate)
      };
    }

    const donations = await Donation.find(query)
      .populate('acceptedBy', 'name')
      .sort({ createdAt: -1 });

    // Create CSV content
    let csv = 'Food Name,Quantity,Food Type,Status,Created Date,Pickup Address,Accepted By,Completed Date,Meals,Carbon Saved (kg)\n';
    
    donations.forEach(donation => {
      csv += `"${donation.foodName}",`;
      csv += `"${donation.quantity}",`;
      csv += `"${donation.foodType}",`;
      csv += `"${donation.status}",`;
      csv += `"${donation.createdAt.toLocaleDateString()}",`;
      csv += `"${donation.pickupAddress}",`;
      csv += `"${donation.acceptedBy?.name || 'N/A'}",`;
      csv += `"${donation.completedAt ? donation.completedAt.toLocaleDateString() : 'N/A'}",`;
      csv += `"${donation.estimatedMeals || 0}",`;
      csv += `"${donation.carbonFootprintSaved || 0}"\n`;
    });

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename=donations-${Date.now()}.csv`);
    res.send(csv);
  } catch (error) {
    console.error(error);
    res.status(500).json({
      success: false,
      message: 'Server error'
    });
  }
};

// @desc    Generate tax certificate
// @route   GET /api/reports/tax-certificate
// @access  Private
const generateTaxCertificate = async (req, res) => {
  try {
    const { year } = req.query;
    
    const startDate = new Date(year, 0, 1);
    const endDate = new Date(year, 11, 31, 23, 59, 59);

    const donations = await Donation.find({
      donorId: req.user._id,
      status: 'completed',
      completedAt: {
        $gte: startDate,
        $lte: endDate
      }
    });

    const totalMeals = donations.reduce((sum, d) => sum + (d.estimatedMeals || 0), 0);
    const estimatedValue = totalMeals * 3; // Assuming $3 per meal

    // Create PDF
    const doc = new PDFDocument({ margin: 50 });
    
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=tax-certificate-${year}.pdf`);
    
    doc.pipe(res);

    // Header
    doc.fontSize(24).text('TAX DEDUCTION CERTIFICATE', { align: 'center' });
    doc.moveDown();

    // Certificate info
    doc.fontSize(14).text(`Certificate Number: SP-${req.user._id}-${year}`, { align: 'center' });
    doc.text(`Year: ${year}`, { align: 'center' });
    doc.moveDown(2);

    doc.fontSize(12);
    doc.text('This certifies that:', { align: 'center' });
    doc.moveDown();
    
    doc.fontSize(14).text(req.user.name, { align: 'center', bold: true });
    doc.fontSize(12).text(req.user.address, { align: 'center' });
    doc.moveDown(2);

    doc.text(`Has donated food valued at approximately $${estimatedValue.toFixed(2)}`, { align: 'center' });
    doc.text(`through the SharePlate platform during the year ${year}`, { align: 'center' });
    doc.moveDown(2);

    doc.fontSize(10);
    doc.text(`Total Completed Donations: ${donations.length}`);
    doc.text(`Total Meals Provided: ${totalMeals}`);
    doc.moveDown(2);

    doc.fontSize(8).text('This certificate is provided for tax purposes. Please consult with a tax professional for specific deduction eligibility.', {
      align: 'center'
    });
    doc.moveDown(2);

    doc.fontSize(10).text(`Issued on: ${new Date().toLocaleDateString()}`, { align: 'center' });
    doc.text('SharePlate Food Donation Platform', { align: 'center' });

    doc.end();
  } catch (error) {
    console.error(error);
    res.status(500).json({
      success: false,
      message: 'Server error'
    });
  }
};

module.exports = {
  generateDonationReport,
  exportToCSV,
  generateTaxCertificate
};
